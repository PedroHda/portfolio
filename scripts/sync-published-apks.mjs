import { readFile, writeFile } from "node:fs/promises";
import { apkSources } from "../src/data/apk-sources.ts";
import { publishedApks } from "../src/data/published-apks.ts";
import { discoverLatestApk } from "../src/services/github-apks.ts";

const files = {};
await Promise.all(Object.entries(apkSources).map(async ([repository, source]) => {
  try {
    files[repository] = await discoverLatestApk("PedroHda", repository, source);
  } catch (error) {
    // Keep the build and downloads usable during API outages or rate limits.
    if (Object.hasOwn(publishedApks, repository)) files[repository] = publishedApks[repository];
    console.warn(`Could not refresh ${repository}; keeping its verified metadata: ${error.message}`);
  }
}));
const ordered = Object.fromEntries(Object.keys(apkSources)
  .filter((repository) => Object.hasOwn(files, repository)).map((repository) => [repository, files[repository]]));
const source = `import type { ApkFile } from "../types/apk";\n\n`
  + `// Generated by npm run sync:apks. Live discovery can replace these verified files.\n`
  + `export const publishedApks: Record<string, ApkFile | null> = ${JSON.stringify(ordered, null, 2)};\n`;
const target = new URL("../src/data/published-apks.ts", import.meta.url);
if (await readFile(target, "utf8") !== source) await writeFile(target, source);
console.log(`Prepared ${Object.values(ordered).filter(Boolean).length} published APK downloads.`);
